#!/usr/bin/env python3
"""Render the measured-kernel tables in docs/KERNELS.md from the archived run.

`docs/evidence/kernels_bench.json` is a *record*: it is rewritten every time the
benchmark runs. `docs/KERNELS.md` quotes numbers out of it. Keeping the two in
agreement by hand fails silently — the previous revision of this file quoted a
table whose archive had already been replaced, and nothing noticed.

So the numbers are generated from the archive rather than typed:

    python3 scripts/kernels_table.py --write   # rewrite the block in KERNELS.md
    python3 scripts/kernels_table.py --check   # exit 1 if it drifted

`make bench` runs `--write` after regenerating the archive, and `make test` runs
`--check`, so a benchmark record that is not reflected in the document is a red
gate rather than a quiet inconsistency.
"""
from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "kernels_bench.json"
DOC = ROOT / "docs" / "KERNELS.md"
BEGIN = "<!-- kernels-table:begin (generated by scripts/kernels_table.py; do not edit by hand) -->"
END = "<!-- kernels-table:end -->"

SHAPES = {
    "qkv_1280x1280": "1280 × 1280 (attention Q/K/V/O)",
    "expert_gate_1920x1280": "1920 × 1280 (expert gate/up)",
    "expert_down_1280x1920": "1280 × 1920 (expert down)",
    "output_head_32000x1280": "32000 × 1280 (output head)",
    "toy_hidden_16x32": "16 × 32 (toy shape, dispatch sanity)",
}
QUANT_SHAPES = {
    "qkv_1280x1280_q8_0": "qkv 1280×1280 Q8_0",
    "qkv_1280x1280_q4_k": "qkv 1280×1280 Q4_K",
    "expert_gate_1792x1280_q4_k": "expert gate 1792×1280 Q4_K",
    "expert_down_1280x1792_q4_k": "expert down 1280×1792 Q4_K",
    "output_head_32000x1280_q4_k": "output head 32000×1280 Q4_K",
}


def fmt_ms(value: float) -> str:
    if value < 0.01:
        return f"{value * 1000:.1f} µs"
    return f"{value:.3f} ms"


def pick(rows: list[dict], shape: str, candidate: str) -> dict | None:
    for row in rows:
        if row["shape"] == shape and row["candidate"] == candidate:
            return row
    return None


def render() -> str:
    doc = json.loads(EVIDENCE.read_text(encoding="utf-8"))
    f32 = doc["results"]
    quant = doc["quant_results"]
    digest = hashlib.sha256(EVIDENCE.read_bytes()).hexdigest()

    isa = doc.get("resolved_isa", "unknown")
    threads = doc.get("resolved_threads", 0)
    iterations = doc.get("iterations", 0)
    host = doc.get("host_cpu", "unknown host")

    out: list[str] = []
    out.append(BEGIN)
    out.append("")
    out.append(
        f"Record: `resolved_isa {isa}`, `resolved_threads {threads}`, "
        f"`--iterations {iterations}`, host `{host}`, "
        f"SHA-256 `{digest[:16]}…` (`docs/evidence/kernels_bench.json`)."
    )
    out.append("")
    out.append("| Shape (out × in) | scalar | ISA, 1 thread | threaded | speedup (scalar → threaded) |")
    out.append("|---|---:|---:|---:|---:|")
    for shape, label in SHAPES.items():
        scalar = pick(f32, shape, "scalar_1t")
        one = pick(f32, shape, "isa_1t") or pick(f32, shape, "avx2_1t")
        threaded = pick(f32, shape, "isa_threads")
        if not (scalar and one and threaded):
            raise SystemExit(f"missing rows for {shape} in {EVIDENCE.name}")
        ratio = float(scalar["best_ms"]) / float(threaded["best_ms"])
        out.append(
            f"| {label} | {fmt_ms(float(scalar['best_ms']))} | "
            f"{fmt_ms(float(one['best_ms']))} | {fmt_ms(float(threaded['best_ms']))} | "
            f"**{ratio:.1f}×** |"
        )
    out.append("")

    # Streaming rate = bytes of weights touched per second on the threaded row.
    # The toy shape is excluded: at 16x32 it measures dispatch overhead, not
    # memory bandwidth, and including it would set the floor of the range.
    streaming = []
    for shape in SHAPES:
        if shape == "toy_hidden_16x32":
            continue
        row = pick(f32, shape, "isa_threads")
        if row:
            streaming.append(float(row["gbytes_per_s"]))
    if streaming:
        out.append(
            f"Across these shapes the threaded path streams "
            f"**{min(streaming):.0f}–{max(streaming):.0f} GB/s** of weights."
        )
        out.append("")

    out.append("| Shape | Scalar | ISA 1 thread | Threaded | Scalar → threaded |")
    out.append("|---|---:|---:|---:|---:|")
    for shape, label in QUANT_SHAPES.items():
        scalar = pick(quant, shape, "scalar_1t")
        one = pick(quant, shape, "avx2_1t") or pick(quant, shape, "isa_1t")
        threaded = pick(quant, shape, "isa_threads")
        if not (scalar and one and threaded):
            raise SystemExit(f"missing quant rows for {shape} in {EVIDENCE.name}")
        ratio = float(scalar["best_ms"]) / float(threaded["best_ms"])
        out.append(
            f"| {label} | {fmt_ms(float(scalar['best_ms']))} | "
            f"{fmt_ms(float(one['best_ms']))} | {fmt_ms(float(threaded['best_ms']))} | "
            f"{ratio:.1f}× |"
        )
    out.append("")

    # The archive carries an explicit avx512_1t row for every shape; without it
    # in the document, prose elsewhere ("AVX-512 wins everywhere", "AVX2 is ~25%
    # slower") had nothing behind it and both statements were wrong.
    pairs = []
    for rows, names in ((f32, SHAPES), (quant, QUANT_SHAPES)):
        for shape, label in names.items():
            a = pick(rows, shape, "avx2_1t")
            b = pick(rows, shape, "avx512_1t")
            if a and b:
                pairs.append((label, float(a["best_ms"]), float(b["best_ms"])))
    if pairs:
        out.append("AVX2+FMA3 against AVX-512, one thread, same shape and layout:")
        out.append("")
        out.append("| Shape | AVX2 | AVX-512 | AVX2 ÷ AVX-512 |")
        out.append("|---|---:|---:|---:|")
        for label, avx2, avx512 in pairs:
            out.append(f"| {label} | {fmt_ms(avx2)} | {fmt_ms(avx512)} | {avx2 / avx512:.2f}× |")
        out.append("")
        slower = sum(1 for _, a, b in pairs if a > b * 1.02)
        faster = sum(1 for _, a, b in pairs if a < b * 0.98)
        out.append(
            f"AVX-512 is the slower of the two on {slower} of {len(pairs)} shapes and "
            f"AVX2 is the slower on {faster}; the rest are within 2%. There is no "
            f"consistent winner at these widths, which is why nothing in this tree "
            f"cites a percentage for \"AVX2 vs AVX-512\"."
        )
        out.append("")

    q4 = [
        pick(quant, shape, "avx2_1t")
        for shape in QUANT_SHAPES
        if shape.endswith("_q4_k")
    ]
    q4_threaded = [
        float(pick(quant, shape, "isa_threads")["gbytes_per_s"])  # type: ignore[index]
        for shape in QUANT_SHAPES
        if shape.endswith("_q4_k")
    ]
    q4_1t = [float(row["gbytes_per_s"]) for row in q4 if row]
    if q4_1t:
        out.append(
            f"Q4_K moves **{min(q4_1t):.1f}–{max(q4_1t):.1f} GB/s** of *stored* bytes at one "
            f"thread and at most **{max(q4_threaded):.1f} GB/s** threaded, against the "
            f"{min(streaming):.0f}–{max(streaming):.0f} GB/s F32 streaming rate above: the "
            f"block decoder, not the memory system, is still the limit."
        )
        out.append("")
    out.append(END)
    return "\n".join(out)


def splice(text: str, block: str) -> str:
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < 0 or end < start:
        raise SystemExit(f"{DOC.relative_to(ROOT)}: generated block markers not found")
    return text[:start] + block + text[end + len(END):]


def main() -> int:
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="rewrite the block in docs/KERNELS.md")
    mode.add_argument("--check", action="store_true", help="exit 1 if the block is stale")
    args = ap.parse_args()

    block = render()
    current = DOC.read_text(encoding="utf-8")
    expected = splice(current, block)

    if args.write:
        if expected != current:
            DOC.write_text(expected, encoding="utf-8")
            print(f"{DOC.relative_to(ROOT)}: kernels table regenerated from {EVIDENCE.name}")
        else:
            print(f"{DOC.relative_to(ROOT)}: kernels table already current")
        return 0

    if expected != current:
        diff = difflib.unified_diff(
            current.splitlines(), expected.splitlines(),
            fromfile=f"{DOC.relative_to(ROOT)} (on disk)",
            tofile=f"{DOC.relative_to(ROOT)} (rendered from {EVIDENCE.name})",
            lineterm="",
        )
        for line in diff:
            print(line)
        print(
            f"\n{DOC.relative_to(ROOT)} quotes numbers that do not match "
            f"{EVIDENCE.relative_to(ROOT)}; run python3 scripts/kernels_table.py --write",
            file=sys.stderr,
        )
        return 1
    print(f"kernels table matches {EVIDENCE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
