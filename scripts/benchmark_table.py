#!/usr/bin/env python3
"""Render the benchmark tables in docs/GAP_ANALYSIS.md from the archived run.

`docs/evidence/benchmark_zen3.json` is the record (written by
`scripts/archive_benchmark.py`); the tables that quote it are generated here so
the numbers cannot be retyped from an older run. The same pattern as
`scripts/kernels_table.py`, and for the same reason: a hand-copied table is a
claim with no artefact behind it.

    python3 scripts/benchmark_table.py --write   # re-render both blocks
    python3 scripts/benchmark_table.py --check   # exit 1 if they drifted

`make test` runs `--check`; `make benchmark` re-renders after a run.
"""
from __future__ import annotations

import argparse
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "benchmark_zen3.json"
DOC = ROOT / "docs" / "GAP_ANALYSIS.md"

METRICS_BEGIN = "<!-- benchmark-metrics:begin (generated by scripts/benchmark_table.py; do not edit by hand) -->"
METRICS_END = "<!-- benchmark-metrics:end -->"
PREFILL_BEGIN = "<!-- prefill-table:begin (generated by scripts/benchmark_table.py; do not edit by hand) -->"
PREFILL_END = "<!-- prefill-table:end -->"


def load() -> dict:
    return json.loads(EVIDENCE.read_text(encoding="utf-8"))


def fmt(value: float, digits: int) -> str:
    return f"{value:,.{digits}f}"


def exp_format(value: float) -> str:
    """`1.43e-03` reads as a precision the measurement does not have."""
    mantissa, exponent = f"{value:.1e}".split("e")
    return f"{mantissa}e{int(exponent)}"


def render_metrics(doc: dict) -> str:
    metrics = doc["metrics"]
    protocol = doc.get("protocol", {})
    dispatch = doc.get("isa_dispatch", {})
    profile = protocol.get("requested_profile", "?")
    commit = doc.get("commit", "?")[:7]
    comparison = doc.get("comparison", {})

    prefill = metrics["prefill_tokens_per_s"]
    p95 = metrics["p95_inter_token_ms"]
    min_tps = float(protocol.get("min_prefill_tps", 0) or 0)
    max_p95 = float(protocol.get("target_p95_ms", 0) or 0)
    comparison_ok = comparison.get("status") == "pass"

    rows = [
        ("Prefill", f"{fmt(prefill['median'], 0)} tok/s",
         f"{fmt(prefill['min'], 0)}–{fmt(prefill['max'], 0)}",
         f"≥ {fmt(min_tps, 0)}", prefill["median"] >= min_tps),
        ("Decode", f"{fmt(metrics['decode_tokens_per_s']['median'], 0)} tok/s",
         f"{fmt(metrics['decode_tokens_per_s']['min'], 0)}–{fmt(metrics['decode_tokens_per_s']['max'], 0)}",
         "—", None),
        ("p95 inter-token", f"{fmt(p95['median'], 3)} ms",
         f"{fmt(p95['min'], 3)}–{fmt(p95['max'], 3)}",
         f"≤ {fmt(max_p95, 0)} ms", p95["median"] <= max_p95),
        ("Median inter-token", f"{fmt(metrics['median_inter_token_ms']['median'], 3)} ms",
         f"{fmt(metrics['median_inter_token_ms']['min'], 3)}–"
         f"{fmt(metrics['median_inter_token_ms']['max'], 3)}", "—", None),
        ("First token", f"{fmt(metrics['first_token_latency_ms']['median'], 1)} ms",
         f"{fmt(metrics['first_token_latency_ms']['min'], 1)}–"
         f"{fmt(metrics['first_token_latency_ms']['max'], 1)}", "—", None),
        ("Peak process RAM", f"{metrics['peak_process_ram_bytes']['median'] / 1e6:.1f} MB",
         f"±{(metrics['peak_process_ram_bytes']['max'] - metrics['peak_process_ram_bytes']['min']) / 2e3:.0f} kB",
         "—", None),
    ]

    out = [METRICS_BEGIN, ""]
    out.append(
        f"Record: commit `{commit}`, requested profile `{profile}`, dispatch "
        + ", ".join(f"`{k}` {v:,}" for k, v in sorted(dispatch.items()))
        + f", archive status `{doc.get('status', '?')}`."
    )
    out.append("")
    out.append("| Metric | Median | Range | Declared target | Verdict |")
    out.append("| --- | --- | --- | --- | --- |")
    for label, median, spread, target, ok in rows:
        verdict = "—" if ok is None else ("pass" if ok else "**fail**")
        out.append(f"| {label} | {median} | {spread} | {target} | {verdict} |")
    out.append(
        "| Reference comparison | "
        f"{comparison.get('prompts_token_match', 0)}/{comparison.get('prompts', 0)} prompts, "
        f"{comparison.get('matching_tokens', 0)}/{comparison.get('reference_tokens', 0)} tokens, "
        f"{comparison.get('prompts', 0) - comparison.get('prompts_routing_match', 0)} routing mismatches, "
        f"max rel diff {exp_format(float(comparison.get('max_rel_diff', 0)))} | — | "
        f"{comparison.get('prompts', 0)}/{comparison.get('prompts', 0)} | "
        f"{'pass' if comparison_ok else '**fail**'} |"
    )
    out.append("")
    out.append(METRICS_END)
    return "\n".join(out)


def render_prefill(doc: dict) -> str:
    bench = doc.get("prefill_bench") or {}
    quote = "> "
    out = [PREFILL_BEGIN, quote]
    if not bench.get("rows"):
        out += [quote + "_No `tools/bench_prefill.py` output is recorded in this archive._",
                quote, PREFILL_END]
        return "\n".join(out)
    shape = bench.get("shape", {})
    out.append(
        quote + f"`tools/bench_prefill.py --kernels {bench.get('kernels', '?')}`, hidden "
        f"{shape.get('hidden', '?')} / intermediate {shape.get('intermediate', '?')} / "
        f"{shape.get('layers', '?')} layers, median of 3 per mode:"
    )
    out += [quote, quote + "| prompt | sequential | batched | speedup |",
            quote + "| --- | --- | --- | --- |"]
    for row in bench["rows"]:
        speedup = row["sequential_ms"] / row["batched_ms"]
        tokens = row.get("prompt_tokens")
        label = f"{tokens} tokens (x{int(row['reps'])})" if tokens else f"x{int(row['reps'])}"
        out.append(
            quote + f"| {label} | {row['sequential_ms']:.1f} ms | "
            f"{row['batched_ms']:.1f} ms | **{speedup:.2f}x** |"
        )
    out += [quote, PREFILL_END]
    return "\n".join(out)


def splice(text: str, begin: str, end: str, block: str) -> str:
    start = text.find(begin)
    stop = text.find(end)
    if start < 0 or stop < 0 or stop < start:
        raise SystemExit(f"{DOC.relative_to(ROOT)}: markers for {begin.split()[-3]} not found")
    return text[:start] + block + text[stop + len(end):]


def main() -> int:
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()

    doc = load()
    current = DOC.read_text(encoding="utf-8")
    expected = splice(current, METRICS_BEGIN, METRICS_END, render_metrics(doc))
    expected = splice(expected, PREFILL_BEGIN, PREFILL_END, render_prefill(doc))

    if args.write:
        if expected != current:
            DOC.write_text(expected, encoding="utf-8")
            print(f"{DOC.relative_to(ROOT)}: benchmark tables regenerated from {EVIDENCE.name}")
        else:
            print(f"{DOC.relative_to(ROOT)}: benchmark tables already current")
        return 0

    if expected != current:
        for line in difflib.unified_diff(current.splitlines(), expected.splitlines(),
                                         fromfile=f"{DOC.relative_to(ROOT)} (on disk)",
                                         tofile="rendered from the archive", lineterm=""):
            print(line)
        print(f"\n{DOC.relative_to(ROOT)} does not match {EVIDENCE.relative_to(ROOT)}; "
              f"run python3 scripts/benchmark_table.py --write", file=sys.stderr)
        return 1
    print(f"benchmark tables match {EVIDENCE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
