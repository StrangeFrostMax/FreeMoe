#!/usr/bin/env python3
"""Generate the lookup grids the IQ-family block codecs index into.

The IQ formats do not store values; they store indices into a fixed grid of
small integers. The grids are arbitrary tables, not formulas, so they have to
come from the reference implementation rather than be derived. This script
extracts them from llama.cpp's `ggml/src/ggml-common.h` (MIT) and writes
`src/quant_tables.cpp`, so the transcription is mechanical and checkable instead
of hand-copied.

Usage:
    python3 tools/gen_quant_tables.py --upstream /path/to/llama.cpp
    python3 tools/gen_quant_tables.py --upstream ... --check   # byte-exact verify
    python3 tools/gen_quant_tables.py --check                  # structural verify only

Only tables that a decoder in `src/quant.cpp` actually indexes are emitted.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "quant_tables.cpp"

# name -> (C type, count, element type used when emitting)
TABLES = [
    ("kmask_iq2xs", "uint8_t", 8),
    ("ksigns_iq2xs", "uint8_t", 128),
    ("kvalues_iq4nl", "int8_t", 16),
    ("iq2xxs_grid", "uint64_t", 256),
    ("iq2xs_grid", "uint64_t", 512),
    ("iq2s_grid", "uint64_t", 1024),
    ("iq3xxs_grid", "uint32_t", 256),
    ("iq3s_grid", "uint32_t", 512),
    ("iq1s_grid", "uint64_t", 2048),
]

HEADER = """// Generated by tools/gen_quant_tables.py -- do not edit by hand.
//
// Lookup grids for the IQ-family block formats. The values are the published
// grids from llama.cpp's ggml/src/ggml-common.h (MIT licence), transcribed
// mechanically; a decoder that indexes them can be checked against the
// reference implementation value for value.
//
// Regenerate with:
//   python3 tools/gen_quant_tables.py --upstream /path/to/llama.cpp

#include "fm/quant_tables.hpp"
"""


def parse_header(path: Path) -> dict[str, list[int]]:
    """Pull every GGML_TABLE_BEGIN block out of ggml-common.h."""
    text = path.read_text()
    tables: dict[str, list[int]] = {}
    for match in re.finditer(
        r"GGML_TABLE_BEGIN\(\s*(?P<type>\w+)\s*,\s*(?P<name>\w+)\s*,\s*(?P<size>[\w/ ]+)\s*\)"
        r"(?P<body>.*?)GGML_TABLE_END\(\)",
        text,
        re.S,
    ):
        name = match.group("name")
        if name not in {entry[0] for entry in TABLES} or name in tables:
            # Skip the macro-definition lines and the alternative GPU layout.
            continue
        body = match.group("body")
        values: list[int] = []
        for token in re.split(r"[,\s]+", body.strip()):
            if not token:
                continue
            if token.startswith("0x") or token.startswith("0X"):
                values.append(int(token, 16))
            else:
                values.append(int(token, 0))
        tables[name] = values
    return tables


def render(tables: dict[str, list[int]]) -> str:
    parts = [HEADER, "\nnamespace fm {\n"]
    for name, ctype, count in TABLES:
        if name not in tables:
            raise SystemExit(f"table {name} is missing from the upstream header")
        values = tables[name]
        if len(values) != count:
            raise SystemExit(f"table {name} has {len(values)} entries, expected {count}")
        parts.append(f"\n// {count} entries.\n")
        parts.append(f"const {ctype} {name}[{count}] = {{\n")
        per_line = 8 if ctype in ("uint64_t", "uint32_t") else 16
        for i in range(0, count, per_line):
            chunk = values[i : i + per_line]
            if ctype.startswith("uint"):
                width = 18 if ctype == "uint64_t" else 11
                text = ", ".join(f"0x{v:0{width}x}".replace("x", "x") for v in chunk)
            else:
                text = ", ".join(str(v) for v in chunk)
            parts.append("    " + text + ",\n")
        parts.append("};\n")
    parts.append("\n} // namespace fm\n")
    return "".join(parts)


# Element domains, so a truncated or mistyped transcription is caught by the
# committed file alone. Upstream need not be present for this check.
DOMAINS = {
    "uint8_t": (0, 0xFF),
    "int8_t": (-128, 127),
    "uint32_t": (0, 0xFFFFFFFF),
    "uint64_t": (0, 0xFFFFFFFFFFFFFFFF),
}

_EMITTED = re.compile(
    r"const\s+(?P<type>uint8_t|int8_t|uint32_t|uint64_t)\s+(?P<name>\w+)\s*"
    r"\[(?P<count>\d+)\]\s*=\s*\{(?P<body>.*?)\};",
    re.S,
)


def check_structural(path: Path = OUT) -> list[str]:
    """Verify the committed tables without a llama.cpp checkout.

    Everything here is a property of the file that the generator promises: every
    declared table is present exactly once with the declared element count, every
    value fits its C type, `kvalues_iq4nl` stays strictly increasing (the decoder
    binary-searches it), and `kmask_iq2xs` is the powers-of-two mask table. The
    byte-for-byte comparison against upstream is `--upstream ... --check`; this
    is the part that can run in CI without a second checkout.
    """
    problems: list[str] = []
    if not path.exists():
        return [f"{path.relative_to(ROOT)} is missing"]
    text = path.read_text()
    seen: dict[str, list[int]] = {}
    for match in _EMITTED.finditer(text):
        name = match.group("name")
        seen[name] = [int(token, 0) for token in
                      re.split(r"[,\s]+", match.group("body").strip()) if token]
        declared = int(match.group("count"))
        if declared != len(seen[name]):
            problems.append(f"{name}: declares {declared} entries, holds {len(seen[name])}")
    for name, ctype, count in TABLES:
        if name not in seen:
            problems.append(f"{name}: missing from the committed header")
            continue
        values = seen[name]
        if len(values) != count:
            problems.append(f"{name}: {len(values)} entries, expected {count}")
        lo, hi = DOMAINS[ctype]
        bad = [v for v in values if v < lo or v > hi]
        if bad:
            problems.append(f"{name}: {len(bad)} value(s) outside {ctype}, first {bad[0]}")
        if len(set(values)) < 2 and count > 2:
            problems.append(f"{name}: every entry is {values[0] if values else 'missing'}")
    iq4 = seen.get("kvalues_iq4nl", [])
    if any(iq4[i] >= iq4[i + 1] for i in range(len(iq4) - 1)):
        problems.append("kvalues_iq4nl: not strictly increasing")
    if seen.get("kmask_iq2xs") != [1 << i for i in range(8)]:
        problems.append("kmask_iq2xs: not the powers-of-two mask table")
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--upstream", help="path to a llama.cpp checkout")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args(argv)

    if args.check and not args.upstream:
        problems = check_structural()
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            return 1
        print(f"{OUT.relative_to(ROOT)} passes the structural check "
              f"({len(TABLES)} tables, upstream not present)")
        return 0
    if not args.upstream:
        parser.error("--upstream is required unless --check is used for the structural check")

    header = Path(args.upstream) / "ggml" / "src" / "ggml-common.h"
    if not header.exists():
        raise SystemExit(f"{header} does not exist")
    text = render(parse_header(header))

    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("quant_tables.cpp is out of date", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0

    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
