#!/usr/bin/env python3
"""Generate `src/unicode_tables.inc` from Python's `unicodedata`.

The BPE pre-tokenisers in `src/tokenizer.cpp` need the same six Unicode
classes llama.cpp uses (`\\p{L}`, `\\p{N}`, `\\p{P}`, `\\p{M}`, `\\p{S}` and
whitespace). Hand-writing them is not an option: a wrong class silently moves a
word boundary and produces a different token id, which is exactly the failure
mode this table exists to remove.

`unicodedata` is the authority here, so the table is generated rather than
typed. Regenerate with:

    python3 tools/gen_unicode_tables.py          # rewrite the include
    python3 tools/gen_unicode_tables.py --check  # fail if it is stale

The output is a set of sorted, non-overlapping `[first, last]` ranges, which
`unicode_class()` binary-searches.

## Which Unicode version

The classes come from a *versioned* database: CPython 3.11 ships Unicode 14.0,
3.12 ships 15.0, 3.13 ships 15.1, and every one of them assigns code points the
previous one did not. A `--check` that re-rendered with whatever the local
interpreter happens to carry would therefore fail on a machine with a different
Python than the one that generated the file -- a red build that says nothing
about the code under test. That actually happened: the table was generated on
3.11 and CI (3.12) reported it "stale" on every run.

So the table names its source in the header, and `--check` behaves like this:

* interpreter's Unicode version == the table's version -> byte comparison, and a
  mismatch is an error (the file really is stale or hand-edited);
* versions differ -> `SKIP`, because regenerating with different data cannot
  answer the question. Exit status stays 0 and the line says `SKIP`, so nobody
  mistakes it for a pass.

A caller that needs real verification pins the data source:

    pip install "unicodedata2==15.1.0"
    FREEMOE_REQUIRE_UNICODE=15.1.0 python3 tools/gen_unicode_tables.py --check

`unicodedata2` is only used when installed; it exists precisely so a pinned
version can be used from any interpreter. CI does this, so the PR checks verify
the table while a developer on any Python still gets a usable local gate.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "unicode_tables.inc"

# The pinned database. `unicodedata2` is a backport that carries a chosen
# Unicode version on any interpreter; the standard library is the fallback.
PINNED_VERSION = "15.1.0"
VERSION_ENV = "FREEMOE_REQUIRE_UNICODE"


def unicode_data():
    """Return the (module, version) that the tables are rendered from."""
    try:
        import unicodedata2 as module  # type: ignore[import-not-found]
        return module, module.unidata_version
    except ImportError:
        import unicodedata as module
        return module, module.unidata_version

UNICODE, UNICODE_VERSION = unicode_data()

MAX_CP = 0x110000

# Category prefixes. `\p{L}` is every L*, and so on for the rest.
CLASSES = {
    "kRangesLetter": ("L",),
    "kRangesNumber": ("N",),
    "kRangesPunctuation": ("P",),
    "kRangesMark": ("M",),
    "kRangesSymbol": ("S",),
}

# `\s` in the pre-tokeniser regexes is Unicode whitespace. Python's
# `str.isspace()` is the closest published definition and matches the set
# llama.cpp flags (C0 separators plus the Z categories and U+0085).
def is_space(cp: int) -> bool:
    return chr(cp).isspace()


def ranges_for(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start: int | None = None
    for cp in range(MAX_CP):
        if 0xD800 <= cp <= 0xDFFF:  # surrogate range: never a code point
            hit = False
        else:
            hit = predicate(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CP - 1))
    return out


def category_predicate(prefixes: tuple[str, ...]):
    def predicate(cp: int) -> bool:
        return UNICODE.category(chr(cp)).startswith(prefixes)

    return predicate


def render() -> str:
    lines = [
        "// Generated by tools/gen_unicode_tables.py; do not edit by hand.",
        f"// Unicode {UNICODE_VERSION} (the version this file must be checked against).",
        "//",
        "// Each table is a sorted, non-overlapping list of inclusive code point",
        "// ranges. `classes()` in src/unicode.cpp binary-searches them.",
        "//",
        "// Included inside an anonymous namespace, so the tables stay internal.",
        "",
    ]
    for name, prefixes in CLASSES.items():
        ranges = ranges_for(category_predicate(prefixes))
        lines.append(f"const RuneRange {name}[] = {{")
        for first, last in ranges:
            lines.append(f"    {{0x{first:04X}, 0x{last:04X}}},")
        lines.append("};")
        lines.append("")

    spaces = ranges_for(is_space)
    lines.append("const RuneRange kRangesSpace[] = {")
    for first, last in spaces:
        lines.append(f"    {{0x{first:04X}, 0x{last:04X}}},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def recorded_version() -> str | None:
    """The Unicode version the committed table was generated from, if known."""
    if not OUT.exists():
        return None
    for line in OUT.read_text(encoding="utf-8").splitlines()[:4]:
        prefix = "// Unicode "
        if line.startswith(prefix):
            return line[len(prefix):].split(" ", 1)[0]
    return None


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when the committed table is stale")
    parser.add_argument("--require-unicode", metavar="VERSION",
                        default=os.environ.get(VERSION_ENV) or None,
                        help="fail unless the Unicode data in use is VERSION "
                             f"(default: ${VERSION_ENV})")
    args = parser.parse_args()

    if args.require_unicode and UNICODE_VERSION != args.require_unicode:
        print(f"Unicode data in use is {UNICODE_VERSION}, but {args.require_unicode} "
              f"is required; pip install \"unicodedata2=={args.require_unicode}\" "
              f"or unset ${VERSION_ENV}", file=sys.stderr)
        return 1

    if not args.check:
        OUT.write_text(render(), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} (Unicode {UNICODE_VERSION}, "
              f"{len(render().splitlines())} lines)")
        return 0

    expected = recorded_version()
    if expected is not None and expected != UNICODE_VERSION:
        # Different databases cannot be compared: say so instead of calling the
        # committed file stale.
        print(f"SKIP {OUT.relative_to(ROOT)}: generated from Unicode {expected}, "
              f"this interpreter has {UNICODE_VERSION}")
        print(f"     verify with: pip install \"unicodedata2=={expected}\" && "
              f"{VERSION_ENV}={expected} python3 tools/gen_unicode_tables.py --check")
        return 0

    text = render()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current != text:
        print(f"{OUT.relative_to(ROOT)} is stale; run tools/gen_unicode_tables.py",
              file=sys.stderr)
        return 1
    print(f"{OUT.relative_to(ROOT)} is up to date (Unicode {UNICODE_VERSION})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
