#!/usr/bin/env python3
"""Generate `src/unicode_tables.inc` from Python's `unicodedata`.

The BPE pre-tokenisers in `src/tokenizer.cpp` need the same six Unicode
classes llama.cpp uses (`\\p{L}`, `\\p{N}`, `\\p{P}`, `\\p{M}`, `\\p{S}` and
whitespace). Hand-writing them is not an option: a wrong class silently moves a
word boundary and produces a different token id, which is exactly the failure
mode this table exists to remove.

`unicodedata` is the authority here, so the table is generated rather than
typed. Regenerate with:

    python3 tools/gen_unicode_tables.py          # rewrite the include
    python3 tools/gen_unicode_tables.py --check  # fail if it is stale

The output is a set of sorted, non-overlapping `[first, last]` ranges, which
`unicode_class()` binary-searches.
"""
from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "unicode_tables.inc"

MAX_CP = 0x110000

# Category prefixes. `\p{L}` is every L*, and so on for the rest.
CLASSES = {
    "kRangesLetter": ("L",),
    "kRangesNumber": ("N",),
    "kRangesPunctuation": ("P",),
    "kRangesMark": ("M",),
    "kRangesSymbol": ("S",),
}

# `\s` in the pre-tokeniser regexes is Unicode whitespace. Python's
# `str.isspace()` is the closest published definition and matches the set
# llama.cpp flags (C0 separators plus the Z categories and U+0085).
def is_space(cp: int) -> bool:
    return chr(cp).isspace()


def ranges_for(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start: int | None = None
    for cp in range(MAX_CP):
        if 0xD800 <= cp <= 0xDFFF:  # surrogate range: never a code point
            hit = False
        else:
            hit = predicate(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CP - 1))
    return out


def category_predicate(prefixes: tuple[str, ...]):
    def predicate(cp: int) -> bool:
        return unicodedata.category(chr(cp)).startswith(prefixes)

    return predicate


def render() -> str:
    lines = [
        "// Generated by tools/gen_unicode_tables.py from Python's unicodedata.",
        f"// Unicode {unicodedata.unidata_version}. Do not edit by hand.",
        "//",
        "// Each table is a sorted, non-overlapping list of inclusive code point",
        "// ranges. `classes()` in src/unicode.cpp binary-searches them.",
        "//",
        "// Included inside an anonymous namespace, so the tables stay internal.",
        "",
    ]
    for name, prefixes in CLASSES.items():
        ranges = ranges_for(category_predicate(prefixes))
        lines.append(f"const RuneRange {name}[] = {{")
        for first, last in ranges:
            lines.append(f"    {{0x{first:04X}, 0x{last:04X}}},")
        lines.append("};")
        lines.append("")

    spaces = ranges_for(is_space)
    lines.append("const RuneRange kRangesSpace[] = {")
    for first, last in spaces:
        lines.append(f"    {{0x{first:04X}, 0x{last:04X}}},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when the committed table is stale")
    args = parser.parse_args()

    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run tools/gen_unicode_tables.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0

    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
